// Shuffle helper using Fisher-Yates
export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Scramble word into LetterTile array ensuring it never matches the target word
export function scrambleWord(word: string, teamPrefix: string): LetterTile[] {
  const upper = word.toUpperCase();
  const chars = upper.split('');
  let attempts = 0;
  let scrambled = [...chars];

  // Try shuffling until it is different from original
  while (attempts < 20) {
    scrambled = shuffleArray(chars);
    if (scrambled.join('') !== upper || chars.length <= 1) {
      break;
    }
    attempts++;
  }

  // If word has all identical letters (rare like "BEE") or still same, swap first two
  if (scrambled.join('') === upper && chars.length > 1) {
    const temp = scrambled[0];
    scrambled[0] = scrambled[1];
    scrambled[1] = temp;
  }

  return scrambled.map((char, index) => ({
    id: `${teamPrefix}-tile-${index}-${char}-${Math.random().toString(36).substring(2, 6)}`,
    char,
    originalIndex: index,
  }));
}

// Get filtered and randomized list of words for the match
export function getMatchWords(
  difficulty: DifficultyLevel,
  category: string,
  count = 30
): WordItem[] {
  let pool = [...WORDS_DATABASE];

  if (difficulty !== 'all') {
    pool = pool.filter((w) => w.difficulty === difficulty);
  }

  if (category && category !== 'All Categories') {
    pool = pool.filter((w) => w.category === category);
  }

  // Fallback to all if pool is too small
  if (pool.length === 0) {
    pool = [...WORDS_DATABASE];
  }

  return shuffleArray(pool).slice(0, Math.max(count, 10));
}
